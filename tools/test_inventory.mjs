// Explicit test fixtures only; not loaded into the application datasets.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const base=new URL('../',import.meta.url),ctx={};
for(const file of ['inventory-engine.js','meal-planner.js'])vm.runInNewContext(fs.readFileSync(new URL('js/'+file,base),'utf8'),ctx);
const E=ctx.InventoryEngine;
assert.equal(E.normalize(null,'g'),null);
assert.equal(E.normalize('','g'),null);
assert.equal(E.parseAmount('0.5kg').amount,500);
assert.equal(E.parseAmount('1/2L').amount,500);
assert.equal(E.parseAmount('1 1/2모').amount,1.5);
for(const raw of ['반 모','1~2개','적당량','-1g','1/0g','Infinityg'])assert.equal(E.parseAmount(raw),null,raw);
assert.equal(E.parseLine('소금 적당량').name,'소금');
assert.equal(E.parseLine('양파 1개(200g)').amount,null);
const dictionary=[{name:'계란',aliases:['달걀']}];
const recipe={id:100001,name:'검사용 레시피',flag:'U',servings:2,ingredientsText:'두부 100g, 달걀 2개',steps:[{text:'검사용'}],meta:{source:'user'}};
const stock=[{name:'두부',qty:'0.2kg',exp:'2026-11-20'},{name:'계란',qty:'4개',exp:null}];
const options={people:4,date:'2026-11-15',dictionary};
assert.equal(E.evaluate(recipe,stock,options).status,'ready');
assert.equal(E.evaluate(recipe,stock,{...options,people:5}).status,'shortage');
assert.notEqual(E.evaluate({...recipe,servings:null},stock,options).status,'ready');
assert.equal(E.evaluate(recipe,[{name:'두부',qty:'1모'},{name:'계란',qty:'4개'}],options).status,'unknown');
assert.equal(E.evaluate(recipe,stock,{...options,date:'2026-11-21'}).status,'shortage');
const before=JSON.stringify(stock);
const next=E.consume(stock,[{name:'두부',amount:50,unit:'g'}],options);
assert.equal(next[0].qty,'150g');assert.equal(JSON.stringify(stock),before);
assert.throws(()=>E.consume(stock,[{name:'두부',amount:100,unit:'g'},{name:'두부',amount:150,unit:'g'}],options));
assert.equal(JSON.stringify(stock),before);
assert.throws(()=>E.consume(stock,[{name:'두부',amount:1,unit:'모'}],options));
const fifo=E.consume([{name:'두부',qty:'50g',exp:'2026-11-16'},{name:'두부',qty:'100g',exp:'2026-11-20'}],[{name:'두부',amount:80,unit:'g'}],options);
assert.equal(fifo.length,1);assert.equal(fifo[0].qty,'70g');
const recommendations=E.buyOne([recipe],[stock[0]],{...options,people:2});
assert.equal(recommendations.length,1);assert.equal(recommendations[0].name,'계란');
assert.equal(recommendations[0].recipes[0].quantityVerified,true);
assert.equal(recommendations[0].recipes[0].needed[0].amount,2);
assert.equal(E.buyOne([recipe],[],options).length,0);
const r2={...recipe,id:100002,name:'검사용 두 번째 레시피',ingredientsText:'두부 100g',servings:1};
const r1={...r2,id:100003,name:'검사용 첫 번째 레시피'};
const plan=ctx.MealPlanEngine.build({recipes:[r1,r2],stock:[{name:'두부',qty:'150g'}],people:1,count:2,start:'2026-11-15',today:'2026-11-15',matches:(r,n)=>r.ingredientsText.includes(n)});
assert.equal(plan.meals.filter(m=>m.recipeId).length,1,'must not allocate the same stock twice');
assert.equal(plan.meals[0].remainingQuantity[0].qty,'50g');
assert.equal(plan.meals[0].quantityStatus,'verified');
console.log('PASS: unit parsing, servings, shortages, aliases, expiry, exact deduction, rollback purity, FIFO, buy-one and sequential stock forecasts.');
